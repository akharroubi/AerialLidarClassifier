# ASPRS standard classification dimension name.
ASPRS_CLASSIFICATION_FIELD = "classification"

# Minimum LAS point record format that exposes a full 8-bit (0-255)
# classification field per the ASPRS LAS 1.4 specification. Older
# formats (0-5) only carry 5 bits and cannot encode codes > 31.
ASPRS_PF6 = 6


def _ensure_asprs_classification_capacity(las, laspy_module, max_code: int,
                                          preserve_legacy_angle: bool = True):
    """Return a LAS object whose point format can hold ``max_code``.

    The ASPRS LAS specification only guarantees a full classification
    range (0-255) in point record formats 6 and above. If the source
    file uses an older PRF and we need to write a code outside the
    5-bit range, transparently convert to PRF 6 / LAS 1.4 so the output
    is fully ASPRS-compliant.
    """
    if max_code <= 31:
        return las
    try:
        pf_id = las.point_format.id
    except Exception:
        return las
    if pf_id >= ASPRS_PF6:
        return las
    header = upgrade_header_preserving_fields(
        las.header, laspy_module, preserve_legacy_angle=preserve_legacy_angle)
    points = convert_points_preserving_fields(las.points, header.point_format,
                                               header.scales, header.offsets, laspy_module,
                                               preserve_legacy_angle=preserve_legacy_angle)
    return laspy_module.LasData(header, points)



