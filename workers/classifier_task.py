def _compute_tile_grid(
    xy: np.ndarray, n_points: int,
    auto: bool, manual_tile_size_m: float | None,
) -> tuple[list[tuple[float, float, float, float]], float]:
    """Compute spatial tile bounds for an XY array.

    Returns (tiles, tile_size_m) where each tile is (x0, y0, x1, y1).
    Tiles cover the full XY extent without overlap (overlap is added
    separately as a buffer per tile when filtering points).
    """
    xmin, ymin = float(xy[:, 0].min()), float(xy[:, 1].min())
    xmax, ymax = float(xy[:, 0].max()), float(xy[:, 1].max())
    return compute_tile_grid(
        xmin, ymin, xmax, ymax, n_points, auto, manual_tile_size_m
    )


def _classify_tiled(
    pcd: np.ndarray,
    predict_fn,
    progress_callback,
    cancel_callback,
    auto: bool = True,
    tile_size_m: float | None = None,
    buffer_m: float = TILE_DEFAULT_BUFFER_M,
) -> np.ndarray | None:
    """Run ``predict_fn`` on ``pcd`` in spatial tiles with a buffer halo.

    ``predict_fn(xyz_m, progress_cb)`` returns one model class id per
    point (a loaded backend's ``predict``). Returns predictions aligned
    with the input points, or None if cancelled.
    """
    n = len(pcd)
    xy = pcd[:, :2]
    buffer_m, buffer_note = resolve_buffer(buffer_m, predict_fn)
    tiles, resolved_size = _compute_tile_grid(xy, n, auto, tile_size_m)
    log_info(
        f"Tiled inference: {len(tiles)} tile(s), tile size "
        f"~{resolved_size:.0f} m. {buffer_note}"
    )

    # The grid assumes uniform density; split the tiles whose buffered
    # window holds more points than the RAM budget (GitHub issue 10).
    grid = PointCountGrid(float(xy[:, 0].min()), float(xy[:, 1].min()),
                          float(xy[:, 0].max()), float(xy[:, 1].max()))
    grid.add(xy[:, 0], xy[:, 1])
    bytes_per_point = getattr(predict_fn, "bytes_per_point", BYTES_PER_TILE_POINT)
    budget = tile_point_budget(bytes_per_point=bytes_per_point)
    plans = split_dense_tiles(tiles, grid, buffer_m, budget)

    def in_window(window):
        return ((xy[:, 0] >= window[0]) & (xy[:, 0] <= window[2])
                & (xy[:, 1] >= window[1]) & (xy[:, 1] <= window[3]))

    def local_grid(_index, window):
        inside = in_window(window)
        fine = PointCountGrid(*window)
        fine.add(xy[inside, 0], xy[inside, 1])
        return fine
    plans = refine_dense_plans(tiles, plans, grid, buffer_m, budget, local_grid)
    if any(len(plan) > 1 for plan in plans):
        dense = sum(len(plan) > 1 for plan in plans)
        tiles = [piece for plan in plans for piece in plan]
        log_info(
            f"Tiled inference: {dense} dense tile(s) split; {len(tiles)} tile(s) now, "
            f"each within the memory budget of {budget:,} points where the buffer allows."
        )
    del grid

    predictions = np.zeros(n, dtype=np.int32)
    assigned = np.zeros(n, dtype=bool)

    # Every tile places its crops / blocks as an untiled run would.
    set_origin = getattr(predict_fn, "set_reference_origin", None)
    if set_origin is not None:
        set_origin(pcd.min(axis=0))
    try:
        result = _classify_tiles(tiles, pcd, xy, predict_fn, progress_callback,
                                 cancel_callback, buffer_m, predictions, assigned,
                                 budget=budget, bytes_per_point=bytes_per_point)
    finally:
        if set_origin is not None:
            set_origin(None)
    return result


def _classify_tiles(tiles, pcd, xy, predict_fn, progress_callback, cancel_callback,
                    buffer_m, predictions, assigned, budget=None,
                    bytes_per_point=BYTES_PER_TILE_POINT):
    n_tiles = len(tiles)
    for i, (tx0, ty0, tx1, ty1) in enumerate(tiles):
        if cancel_callback():
            return None

        bx0, by0 = tx0 - buffer_m, ty0 - buffer_m
        bx1, by1 = tx1 + buffer_m, ty1 + buffer_m

        in_buffer = (
            (xy[:, 0] >= bx0) & (xy[:, 0] <= bx1)
            & (xy[:, 1] >= by0) & (xy[:, 1] <= by1)
        )
        if not in_buffer.any():
            continue

        buffer_idx = np.where(in_buffer)[0]
        if budget is not None and len(buffer_idx) > budget:
            log_warning(
                f"Tiled inference: tile {i + 1}/{n_tiles} holds {len(buffer_idx):,} points with "
                f"its buffer, more than the memory budget of {budget:,}: the {buffer_m:g} m of "
                "context the model needs around it is that dense, so a smaller tile would not "
                f"hold fewer. It needs about "
                f"{len(buffer_idx) * bytes_per_point / 1024 ** 3:.1f} GB; "
                "the run continues. If it runs out of memory, close other applications."
            )
        in_core_local = (
            (xy[buffer_idx, 0] >= tx0) & (xy[buffer_idx, 0] < tx1)
            & (xy[buffer_idx, 1] >= ty0) & (xy[buffer_idx, 1] < ty1)
        )

        def tile_progress(p, _i=i):
            # Map (0..100) within the tile to the overall progress range.
            overall = (_i + (p / 100.0)) / n_tiles * 100.0
            progress_callback(overall)

        try:
            tile_preds = predict_fn(pcd[buffer_idx], tile_progress)
        except InterruptedError:
            return None

        if tile_preds is None:
            raise ValueError(f"Tile {i + 1}/{n_tiles} returned no predictions.")
        tile_preds = checked_predictions(tile_preds, len(buffer_idx))

        core_global_idx = buffer_idx[in_core_local]
        predictions[core_global_idx] = tile_preds[in_core_local]
        assigned[core_global_idx] = True

        progress_callback(((i + 1) / n_tiles) * 100.0)

    # The grid covers the whole extent with half-open cores, so every
    # point belongs to exactly one core and this should never fire. If
    # it does (a tile returned nothing, NaN coordinates), say so plainly
    # rather than pretending a neighbour's prediction was used: these
    # points keep model id 0, which the caller reports as "unmapped ->
    # ASPRS 0" together with a count.
    if not assigned.all():
        raise ValueError(f"{int((~assigned).sum()):,} points were not covered by tile cores; no output published.")

    return predictions


def _empty_gpu_cache_safe():
    try:
        t = _get_torch()
        if t.cuda.is_available():
            t.cuda.empty_cache()
        mps = getattr(t.backends, "mps", None)
        if mps is not None and mps.is_available() and hasattr(t, "mps"):
            t.mps.empty_cache()
    except Exception:
        _LOG.debug("Ignored non-fatal error", exc_info=True)


class ClassificationTask(QgsTask):
    """Background task that runs the classifier over a list of files."""

    # Every message the task logs (the plugin's log helpers, the backend's
    # messages included), for the dock's log panel. Emitted from the worker
    # thread, delivered queued to the dock.
    log_message = pyqtSignal(str)

    def __init__(self, files, out_dir, suffix, model_id, device, field_name,
                 tile_enabled=False, tile_auto=True,
                 tile_size_m=None, tile_buffer_m=TILE_DEFAULT_BUFFER_M,
                 tile_streaming=False, units_override=None, output_codes=None,
                 prepare_qgis_view=False):
        super().__init__("Classifying LiDAR point clouds",
                         scoped_enum(QgsTask, "Flag", "CanCancel"))
        # "auto" (read the CRS), "metre", "foot" or "us_foot"; see
        # utils.las_units. The model needs metres.
        self.units_override = units_override
        self.files = list(files)
        self.out_dir = Path(out_dir)
        self.suffix = suffix or "_classified"
        # The model (core.registry) brings its weights, its backend and
        # its class-id -> ASPRS mapping.
        self.spec = output_model_spec(get_model(model_id), output_codes)
        # "cuda", "mps" or "cpu" (see classifier_core.resolve_device).
        self.device = device
        self.field_name = validate_model_output_field(self.spec, field_name)
        self.class_mapping = self.spec.class_mapping

        self.tile_enabled = bool(tile_enabled)
        self.tile_auto = bool(tile_auto)
        self.tile_size_m = tile_size_m
        self.tile_buffer_m = float(TILE_DEFAULT_BUFFER_M if tile_buffer_m is None else tile_buffer_m)
        self.tile_streaming = bool(tile_streaming)

        self.output_files = []
        self.prepare_qgis_view = bool(prepare_qgis_view)
        self.view_files = {}
        self.error_message = None
        self.current_file_name = ""
        # Set while a stage other than a file is running (weights download).
        self.status_text = ""
        self.files_processed = 0

    # ------------------------------------------------------------------
    def run(self) -> bool:
        from ..core.run_lock import exclusive_run

        set_thread_sink(self.log_message.emit)
        try:
            # One run at a time (the dock and Processing share the GPU and
            # the RAM the memory plan counts on).
            with exclusive_run(self.isCanceled, log_info):
                return self._run()
        except InterruptedError:
            return False
        finally:
            set_thread_sink(None)

    def _run(self) -> bool:
        backend = None
        try:
            import laspy
            _get_torch()  # ensures torch DLL path is set on Windows

            self.out_dir.mkdir(parents=True, exist_ok=True)

            total = len(self.files)
            if total == 0:
                return True

            planned_outputs = [_resolve_output_path(fp, self.out_dir, self.suffix) for fp in self.files]
            validate_output_paths(self.files, planned_outputs)

            manager = ModelManager(self.spec)
            if not self.spec.supports_device(self.device):
                self.error_message = (
                    f"{self.spec.display_name} does not run on '{self.device}' "
                    f"({self.spec.device_requirement_text()}). Choose another "
                    "model or compute device."
                )
                log_error(self.error_message)
                return False
            # First run of a model: fetch its weights now (no separate
            # download step for the user). The progress bar shows the
            # download, then restarts for the classification.
            if not manager.is_model_available():
                size_mb = self.spec.weights_size_mb

                def download_progress(received, total):
                    total = total if total > 0 else size_mb * 1e6
                    self.status_text = (
                        f"Downloading the {self.spec.short_name} weights "
                        f"(first use): {received / 1e6:.0f} / "
                        f"{total / 1e6:.0f} MB"
                    )
                    self.setProgress(min(99.0, 100.0 * received / total))

                self.status_text = (
                    f"Downloading the {self.spec.short_name} weights "
                    f"(first use, about {size_mb:.0f} MB)...")
                self.setProgress(0)
                try:
                    ok, msg = manager.ensure_available(
                        download_progress, self.isCanceled)
                except InterruptedError:
                    return False
                if not ok:
                    self.error_message = msg
                    log_error(msg)
                    return False
                self.status_text = ""
                self.setProgress(0)

            # Load the network once for the whole run; every tile of every
            # file goes through the same backend.
            backend = create_backend(
                self.spec, manager.get_model_path(), log=log_warning,
            )
            log_info(
                f"Model: {self.spec.display_name} on {self.device.upper()}"
            )
            backend.load(self.device)

            def predict_fn(xyz_m, progress_cb):
                return backend.predict(xyz_m, progress_cb, self.isCanceled)
            # Tiles share the file's origin and use the model's context as
            # buffer (see LitePTBackend.set_reference_origin, resolve_buffer).
            predict_fn.set_reference_origin = getattr(backend, "set_reference_origin", None)
            predict_fn.context_buffer = lambda: getattr(backend, "context_buffer_m", None)
            predict_fn.bytes_per_point = bytes_per_tile_point(self.spec.family)

            for i, fp in enumerate(self.files):
                if self.isCanceled():
                    return False

                self.current_file_name = fp.name
                self.files_processed = i

                log_info(f"Processing {fp.name} ({i + 1}/{total})")

                file_base = (i / total) * 100.0
                file_span = 100.0 / total
                self.setProgress(file_base + file_span * 0.05)

                out_path = _resolve_output_path(
                    fp, self.out_dir, self.suffix
                )

                # Safety: never overwrite the input file.
                try:
                    same = out_path.resolve() == fp.resolve()
                except Exception:
                    same = False
                if same:
                    msg = (
                        f"Refusing to overwrite the input file: "
                        f"{fp.name}. Choose a different output folder or "
                        "suffix."
                    )
                    log_error(msg)
                    self.error_message = msg
                    return False

                if out_path.exists():
                    log_warning(
                        f"Output {out_path.name} already exists - overwriting."
                    )

                try:
                    actual_path = self._process_one(
                        fp, out_path, predict_fn, laspy,
                        file_base, file_span,
                    )
                    if actual_path is not None:
                        self.output_files.append(actual_path)
                        if self.prepare_qgis_view:
                            from ..utils.pointcloud_view import prepare_qgis_view
                            self.status_text = f"Preparing QGIS view: {actual_path.name}"
                            # Emit so the dock shows the step (no other progress meanwhile).
                            self.setProgress(file_base + file_span * 0.98)
                            self.view_files[actual_path] = prepare_qgis_view(
                                actual_path, laspy_module=laspy, cancel_callback=self.isCanceled,
                            )
                            self.status_text = ""
                            if self.isCanceled():
                                return False
                except InterruptedError:
                    log_info("Cancellation requested - stopping.")
                    return False
                except Exception as exc:
                    msg = f"Failed on {fp.name}: {exc}"
                    log_error(msg + "\n" + traceback.format_exc())
                    self.error_message = msg
                    return False

                self.setProgress(file_base + file_span)
                _empty_gpu_cache_safe()

            self.files_processed = total
            return True

        except Exception as exc:
            self.error_message = f"{exc}\n{traceback.format_exc()}"
            log_error(f"Classification error: {self.error_message}")
            _empty_gpu_cache_safe()
            return False
        finally:
            if backend is not None:
                try:
                    backend.unload()
                except Exception:
                    _LOG.debug("Ignored non-fatal error", exc_info=True)

    # ------------------------------------------------------------------
    def _plan(self, fp, laspy) -> str:
        """"untiled", "tiled" or "streaming" for this file.

        Tiling is the user's choice; with it, streaming follows from the
        memory the file needs (see core.memory.plan_processing), so a file
        that does not fit in RAM is streamed from disk without a separate
        option. Without it, a file too large for one piece is refused.
        ``tile_streaming`` (scripts, tests, Processing's TILE_STREAMING)
        forces streaming, with or without tiling. Each automatic switch is
        logged.
        """
        with laspy.open(str(fp)) as reader:
            n_points = int(reader.header.point_count)
            record_length = int(reader.header.point_format.size)
            new_records = output_record_length(
                reader.header.point_format, self.field_name, self.class_mapping)
        mode, reason = plan_processing(
            n_points, record_length, self.tile_enabled,
            force_streaming=self.tile_streaming,
            bytes_per_point=bytes_per_tile_point(self.spec.family),
            output_record_length=new_records)
        if mode == "too_large":
            raise RuntimeError(
                f"Not enough memory to classify {fp.name} in one piece: {reason} "
                "Tick 'Tile large files' and run again: the file is then classified "
                "tile by tile, and streamed from disk when it does not fit in memory.")
        if reason:
            log_info(f"{fp.name}: {reason}")
        return mode

    # ------------------------------------------------------------------
    def _process_one_streaming(
        self, fp, out_path, predict_fn, laspy,
        file_base, file_span,
    ):
        """Streaming variant: process a single file with disk-backed tiling."""
        from .streaming_classifier import streaming_tiled_classify

        # Automatic streaming of a file the user did not tile: auto tiles.
        tile_auto = self.tile_auto or not self.tile_enabled

        log_info(f"Streaming mode active for {fp.name}")

        def stream_progress(p):
            if self.isCanceled():
                raise InterruptedError()
            self.setProgress(file_base + file_span * (p / 100.0))

        field = (self.field_name or ASPRS_CLASSIFICATION_FIELD).strip()

        try:
            written = streaming_tiled_classify(
                input_path=fp,
                output_path=out_path,
                predict_fn=predict_fn,
                device=self.device,
                class_mapping=self.class_mapping,
                field_description=f"AI classification ({self.spec.display_name})",
                model_spec=self.spec,
                laspy_module=laspy,
                progress_callback=stream_progress,
                cancel_callback=self.isCanceled,
                field_name=field,
                tile_auto=tile_auto,
                tile_size_m=None if tile_auto else self.tile_size_m,
                buffer_m=self.tile_buffer_m,
                units_override=self.units_override,
            )
        except InterruptedError:
            raise
        return written

    # ------------------------------------------------------------------
    def _process_one(self, fp, out_path, predict_fn, laspy,
                     file_base, file_span):
        """Run inference on a single file and write the result."""
        # Streaming when the file does not fit in RAM ---------------------
        mode = self._plan(fp, laspy)
        if mode == "streaming":
            return self._process_one_streaming(
                fp, out_path, predict_fn, laspy,
                file_base, file_span,
            )

        # In-memory path -----------------------------------------------------
        validate_output_paths([fp], [out_path])
        with laspy.open(str(fp), laz_backend=laspy.LazBackend.LazrsParallel) as reader:
            field = validate_label_field(reader.header.point_format, self.field_name, laspy)
            las = read_complete(reader)

        if len(las.x) == 0:
            log_warning(f"Skipping {fp.name}: input has zero points.")
            return None

        # The model works in metres. US files are usually in US survey
        # feet; without this conversion every distance is 3.28x too
        # small for it and buildings come out as wires and towers.
        units = resolve_units(las.header, self.units_override)
        if units.angular:
            raise RuntimeError(
                f"{fp.name} is in geographic coordinates (degrees). The "
                "model needs projected coordinates: reproject the file (for "
                "example to the local UTM zone) and run again."
            )
        log_info(f"{fp.name}: coordinate units: {units.describe()}")
        pcd = units.apply(np.transpose(np.array([las.x, las.y, las.z])))

        def progress_cb(p):
            if self.isCanceled():
                raise InterruptedError()
            self.setProgress(file_base + file_span * (0.10 + p * 0.008))

        if mode == "tiled":
            tile_auto = self.tile_auto or not self.tile_enabled
            preds = _classify_tiled(
                pcd, predict_fn, progress_cb, self.isCanceled,
                auto=tile_auto,
                tile_size_m=None if tile_auto else self.tile_size_m,
                buffer_m=self.tile_buffer_m,
            )
        else:
            preds = predict_fn(pcd, progress_cb)

        if preds is None:
            raise ValueError(f"Classifier returned no results for {fp.name}; no output published.")

        self.setProgress(file_base + file_span * 0.92)

        preds = checked_predictions(preds, len(las.points))
        is_asprs_field = field == ASPRS_CLASSIFICATION_FIELD
        asprs_p = label_values(preds, self.class_mapping, raw_ids=not is_asprs_field)

        if is_asprs_field:
            try:
                max_code = int(asprs_p.max())
            except ValueError:
                max_code = 0
            las = _ensure_asprs_classification_capacity(
                las, laspy, max_code,
                preserve_legacy_angle=not supports_output_codes(self.spec))
            las.classification = asprs_p.astype(np.uint8)
        elif field in las.point_format.dimension_names:
            assign_labels(las, field, asprs_p)
        else:
            add_extra_dim_preserving_raw(las, laspy.ExtraBytesParams(
                name=field, type="int32",
                description=extra_dim_description(f"AI classification ({self.spec.display_name})"),
            ))
            assign_labels(las, field, asprs_p)

        add_label_metadata(las.header, self.spec, field)
        _strip_copc_vlrs(las)
        _write_las(las, out_path, laspy, cancel_callback=self.isCanceled)
        return out_path

